import {readdir,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';
const root=fileURLToPath(new URL('../dist/',import.meta.url));
const groups=['neuro','qizhiweiqi','exhibit-01','spectral/form-research','spectral/function','spectral/research'];
const assets={};
for(const group of groups){
 assets[group]={};
 for(const file of (await readdir(path.join(root,'assets',group))).sort()){
  if(!/\.(png|jpe?g|webp|svg)$/i.test(file))continue;
  const src=`assets/${group}/${file}`;
  const record={src};
  if(group==='neuro'&&!file.endsWith('.svg')){
   const meta=await sharp(path.join(root,src)).metadata();
   record.width=meta.width;record.height=meta.height;
   record.preview=`assets/neuro-previews/${file.replace(/\.[^.]+$/,'.webp')}`;
   await mkdir(path.join(root,'assets/neuro-previews'),{recursive:true});
   await sharp(path.join(root,src)).rotate().resize({width:1280,height:4096,fit:'inside',withoutEnlargement:true}).webp({quality:82,effort:2}).toFile(path.join(root,record.preview));
  }
  assets[group][file]=record;
 }
}
// Literal URLs let the publication build fingerprint and optimize every image.
await writeFile(path.join(root,'runtime-image-assets.js'),'// Generated by scripts/prepare-runtime-images.mjs. Keys remain stable; URLs are rewritten at build time.\nexport const runtimeImages = '+JSON.stringify(assets,null,2)+';\n');
console.log('Prepared explicit image references for',groups.join(', '));
